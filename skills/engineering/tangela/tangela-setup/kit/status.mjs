#!/usr/bin/env node
// Prints where the program stands: the orders version, the units by state,
// the ratchets against baseline and target, what needs a person, and spend
// against the budget.
//
//   node .tangela/scripts/status.mjs [--write] [--measure]
//
// --measure reruns each ratchet's command and records the count. --write
// also writes the store's status.md. Exit codes: 0 printed, 1 a ratchet's
// command didn't print one integer, 2 no program or a broken store.

import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";
import { repoRoot } from "./lib/contract.mjs";
import { isMain } from "./lib/main.mjs";
import { ordersVersion, readTable, requireProgram, writeTable } from "./lib/store.mjs";

// The order states are counted in, finished work first.
const STATE_ORDER = ["landed", "running", "reported", "briefed", "planned", "parked", "dropped"];
const BUDGET = /^\s*-?\s*Budget:\s*([\d,]+(?:\.\d+)?)\s*(.*)$/im;
const STOP_LINE = /^\s*-?\s*Stop launching at:\s*(\d+(?:\.\d+)?)\s*%/im;
const DEFAULT_STOP = 70;
// States a unit reaches only after it launched, so it has spent something.
const LAUNCHED = ["running", "reported", "landed"];

export function status({ cwd = process.cwd(), measure = false, write = false, say = console.log } = {}) {
  const root = repoRoot(cwd);
  const { name, store } = requireProgram(root);
  const lines = [];
  const add = (line) => lines.push(line);

  add(`program  ${name}`);
  add(`orders   version ${ordersVersion(store) ?? "unknown"}`);

  const units = readTable(store, "units.tsv");
  const byState = STATE_ORDER.map((state) => [state, units.filter((unit) => unit.state === state)]).filter(
    ([, list]) => list.length,
  );
  const counts = byState.map(([state, list]) => `${list.length} ${state}`).join(", ") || "none";
  add(`units    ${units.length}: ${counts}`);
  for (const [state, list] of byState) {
    for (const unit of list) add(`  ${state.padEnd(9)} ${unit.id}${unit.title ? `  ${unit.title}` : ""}${unit.landed ? ` (${unit.landed})` : ""}`);
  }

  const ratchets = readTable(store, "ratchets.tsv");
  const problems = measure ? measureRatchets(root, store, ratchets) : [];
  const atTarget = ratchets.filter((r) => r.count !== "" && Number(r.count) <= Number(r.target));
  add(`ratchets ${atTarget.length} of ${ratchets.length} at target`);
  for (const r of ratchets) {
    const above = Number(r.count) > Number(r.baseline) ? ", ABOVE BASELINE" : "";
    add(`  ${r.name}: ${r.count || "not measured"}, baseline ${r.baseline}, target ${r.target}${above}${r.measured ? `, measured ${r.measured}` : ""}`);
  }
  for (const problem of problems) add(`  PROBLEM ${problem}`);

  const open = openAttention(store);
  add(`attention ${open.length} open`);
  for (const item of open) add(`  ${item}`);

  add(`spend    ${spendLine(store, units)}`);

  const verdict = `STATUS ${units.length} units: ${counts}; ${atTarget.length} ratchets at target of ${ratchets.length}; ${open.length} need a person`;
  add(verdict);
  for (const line of lines) say(line);
  if (write) {
    const body = ["# Status", "", `Generated by status.mjs at ${new Date().toISOString()}. Don't edit it by hand.`, "", "```text", ...lines, "```", ""];
    writeFileSync(join(store, "status.md"), body.join("\n"));
  }
  return { units: units.length, atTarget: atTarget.length, ratchets: ratchets.length, open: open.length, problems, verdict };
}

function measureRatchets(root, store, ratchets) {
  const problems = [];
  for (const ratchet of ratchets) {
    const result = spawnSync(ratchet.command, { cwd: root, shell: true, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
    const output = (result.stdout ?? "").trim();
    if (result.status !== 0 || !/^\d+$/.test(output)) {
      problems.push(`${ratchet.name}: "${ratchet.command}" exited ${result.status} and printed "${output.slice(0, 80)}", not one integer`);
      continue;
    }
    ratchet.count = output;
    ratchet.measured = new Date().toISOString().slice(0, 10);
  }
  writeTable(store, "ratchets.tsv", ratchets);
  return problems;
}

function openAttention(store) {
  const file = join(store, "attention.md");
  if (!existsSync(file)) return [];
  return readFileSync(file, "utf8").split(/\r?\n/).filter((line) => line.startsWith("- [ ] "));
}

// Units' spend is free text whose leading number is in the budget's unit.
// The orders' stop line sets the share at which launching stops. A launched
// unit with blank spend is unknown, not zero, so the line names it.
function spendLine(store, units) {
  const spent = units.reduce((sum, unit) => sum + number(unit.spend), 0);
  const unknown = units.filter((unit) => LAUNCHED.includes(unit.state) && !(unit.spend ?? "").trim()).map((unit) => unit.id);
  const uncounted = unknown.length
    ? `, not counting ${unknown.length} unit${unknown.length === 1 ? "" : "s"} with no spend recorded: ${unknown.join(", ")}`
    : "";
  const orders = join(store, "orders.md");
  const text = existsSync(orders) ? readFileSync(orders, "utf8") : "";
  const budget = BUDGET.exec(text);
  if (!budget) return `${spent} spent${uncounted}; the orders set no budget`;
  const total = number(budget[1]);
  const unit = budget[2].trim();
  const share = total ? Math.round((100 * spent) / total) : 0;
  const stop = Number(STOP_LINE.exec(text)?.[1] ?? DEFAULT_STOP);
  return `${spent} of ${total}${unit ? ` ${unit}` : ""} (${share}%)${uncounted}${share >= stop ? `, at or past ${stop}%: stop launching` : ""}`;
}

function number(text = "") {
  const match = /[\d,]+(?:\.\d+)?/.exec(text);
  return match ? Number(match[0].replaceAll(",", "")) : 0;
}

if (isMain(import.meta.url)) {
  const { values } = parseArgs({ options: { write: { type: "boolean" }, measure: { type: "boolean" } } });
  try {
    const result = status({ write: values.write, measure: values.measure });
    process.exit(result.problems.length ? 1 : 0);
  } catch (error) {
    console.error(`STATUS BROKEN ${error.message}`);
    process.exit(2);
  }
}
